#!/usr/bin/env node
/**
 * Generates src/lib/assets.ts from assets/manifests/assets-manifest.json.
 * The manifest is the visual source of truth (see docs/release/FINAL_RELEASE_REPORT.md).
 * Canonical ASCII asset IDs only — never code against legacy filenames.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const manifestPath = join(here, "../../../assets/manifests/assets-manifest.json");
const outPath = join(here, "../src/lib/assets.ts");

const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));

const entries = manifest.assets.map((a) => ({
  id: a.id,
  category: a.category,
  png: a.png_path,
  webp: a.webp_path,
  thumbnail: a.thumbnail_path,
  width: a.width,
  height: a.height,
  hasAlpha: a.has_alpha,
  grade: a.grade,
  status: a.status,
  tags: a.tags,
  issues: a.issues ?? [],
}));

const ids = entries.map((e) => `  | "${e.id}"`).join("\n");

const out = `// AUTO-GENERATED by scripts/generate-assets-registry.mjs — do not edit by hand.
// Source of truth: assets/manifests/assets-manifest.json (v${manifest.version}, ${manifest.visual_asset_count} assets).

export type AssetId =
${ids};

export interface AssetEntry {
  id: AssetId;
  category: string;
  png: string;
  webp: string;
  thumbnail: string;
  width: number;
  height: number;
  hasAlpha: boolean;
  grade: "A" | "B" | "C";
  status: "approved" | "review";
  tags: string[];
  issues: string[];
}

export const ASSET_REGISTRY: Record<AssetId, AssetEntry> = ${JSON.stringify(
  Object.fromEntries(entries.map((e) => [e.id, e])),
  null,
  2
)} as const;

export const ASSET_IDS = Object.keys(ASSET_REGISTRY) as AssetId[];

export function getAsset(id: AssetId): AssetEntry {
  return ASSET_REGISTRY[id];
}

/** Runtime src for an asset — WebP preferred in UI (ASSET_INTEGRATION_GUIDE rule 1). */
export function asset(id: AssetId): string {
  return ASSET_REGISTRY[id].webp;
}

/** Master/fallback PNG src (rule 2). */
export function assetMaster(id: AssetId): string {
  return ASSET_REGISTRY[id].png;
}
`;

writeFileSync(outPath, out);
console.log(`Wrote ${entries.length} assets to ${outPath}`);
